export function getPetById(id: string): Pet | undefined {
  return pets.find((p) => p.id === id);
}

export function getPetsByClientId(clientId: string): Pet[] {
  return pets.filter((p) => p.clientId === clientId && p.isActive);
}

export function getActivePets(): Pet[] {
  return pets.filter((p) => p.isActive);
}

export function getPetsWithSafetyFlags(): Pet[] {
  return pets.filter((p) => p.safetyFlags.length > 0 && p.isActive);
}

export function getPetsWithExpiredVaccinations(): Pet[] {
  const now = new Date();
  return pets.filter((p) =>
    p.vaccinations.some((v) => new Date(v.expirationDate) < now) && p.isActive
  );
}

export function getPetsByGroomer(groomerId: string): Pet[] {
  return pets.filter((p) => p.preferredGroomerId === groomerId && p.isActive);
}
