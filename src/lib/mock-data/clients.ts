export function getClientById(id: string): Client | undefined {
  return clients.find((c) => c.id === id);
}

export function getActiveClients(): Client[] {
  return clients.filter((c) => c.isActive);
}

export function searchClients(query: string): Client[] {
  const lowerQuery = query.toLowerCase();
  return clients.filter(
    (c) =>
      c.firstName.toLowerCase().includes(lowerQuery) ||
      c.lastName.toLowerCase().includes(lowerQuery) ||
      c.email.toLowerCase().includes(lowerQuery) ||
      c.phone.includes(query)
  );
}

export function getClientsByTag(tag: string): Client[] {
  return clients.filter((c) => c.tags.includes(tag));
}

export function getVIPClients(): Client[] {
  return clients.filter((c) => c.tags.includes("VIP") && c.isActive);
}

export function getRecentClients(limit: number = 10): Client[] {
  return [...clients]
    .sort((a, b) => new Date(b.updatedAt).getTime() - new Date(a.updatedAt).getTime())
    .slice(0, limit);
}
